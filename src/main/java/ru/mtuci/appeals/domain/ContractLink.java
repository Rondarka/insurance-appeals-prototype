package ru.mtuci.appeals.domain;

/** Привязка договора к обращению (решение 29). */
public enum ContractLink {
    /** Договор в обращении. */
    LINKED,
    /** Учётная система была недоступна — подсистема подберёт договор, когда она вернётся. */
    PENDING,
    /** Подходит несколько договоров — выбирает клиент, если не ответил — сотрудник. */
    NEEDS_CHOICE,
    /** Договора указанного вида нет — выбор из всех договоров клиента. */
    NOT_FOUND
}
