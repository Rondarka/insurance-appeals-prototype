-- Тексты помощника (решение 35) без лишних тире: их видит сотрудник, а шаблон ответа
-- уходит клиенту. Прежняя миграция не меняется: у неё уже есть контрольная сумма.
update text_signal set hint = 'Ответ может проверить регулятор: каждый вывод должен быть обоснован, срок по закону соблюдён.'
where code = 'REGULATOR';
update text_signal set hint = 'Клиент готовится к спору. Проверьте, не претензия ли это: по ней нужен мотивированный ответ в срок по 123-ФЗ.'
where code = 'OMBUDSMAN';
update text_signal set hint = 'Сохраните обоснование и документы: они понадобятся юристам.'
where code = 'COURT';
update text_signal set hint = 'Сверьте сумму с условиями договора: страховая сумма, франшиза и оплата премии есть в разделе «Договор».'
where code = 'PAYMENT_DEMAND';
update text_signal set hint = 'Проблема не решена с первого раза: посмотрите историю клиента.'
where code = 'REPEATED';

-- в шаблонах тире стоят внутри подсказок в квадратных скобках и перед основанием
update answer_template
set body = replace(replace(replace(replace(replace(body,
        ' — например, ', ', например: '),
        'расчёт — ', 'расчёт: '),
        'претензии — ', 'претензии: '),
        'страхования — ', 'страхования: '),
        ' — ', ', ')
where body like '%—%';
