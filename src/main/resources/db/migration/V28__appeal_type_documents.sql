-- сотрудник запросит недостающее. Чем полнее комплект сразу, тем меньше переписки.
create table appeal_type_document (
    category varchar(50) not null,
    type_code varchar(60) not null,
    sort_order integer not null,
    label varchar(200) not null,
    primary key (category, type_code, sort_order),
    foreign key (category, type_code) references appeal_type(category, code)
);

