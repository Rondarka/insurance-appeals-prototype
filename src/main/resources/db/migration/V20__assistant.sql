-- Найденные сигналы: один сигнал на обращение, с цитатой — почему он сработал.
create table appeal_signal (
    appeal_id uuid not null references appeal(id) on delete cascade,
    signal_code varchar(30) not null references text_signal(code),
    excerpt varchar(300) not null,
    detected_at timestamp with time zone not null,
    primary key (appeal_id, signal_code)
);

