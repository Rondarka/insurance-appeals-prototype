package ru.mtuci.appeals.domain;

/** Уровень эскалации по сроку закона (решение 14): только растёт, каждый уровень наступает один раз. */
public enum EscalationLevel {
    NONE,
    /** До срока по закону осталось несколько рабочих дней: руководитель предупреждён. */
    AT_RISK,
    /** Срок по закону истёк, а ответа по существу нет. */
    BREACHED
}
