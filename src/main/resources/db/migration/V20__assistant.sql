-- Показанные подсказки и решение сотрудника по ним: по доле принятых решают,
-- вкладываться ли в локальную модель. Одна строка на обращение и вид подсказки.
create table assistant_suggestion (
    appeal_id uuid not null references appeal(id) on delete cascade,
    kind varchar(30) not null check (kind in ('TYPE_HINT', 'SIMILAR', 'DRAFT')),
    source varchar(20) not null check (source in ('RULES', 'LOCAL_MODEL')),
    shown_at timestamp with time zone not null,
    shown_to varchar(100) not null,
    decision varchar(20) check (decision in ('ACCEPTED', 'REJECTED')),
    decided_at timestamp with time zone,
    decided_by varchar(100),
    primary key (appeal_id, kind)
);

-- Кто даёт подсказки: правила и поиск или локальная модель. Меняет администратор,
-- изменение — в журнал настроек (решение 34).
create table assistant_setting (
    id integer primary key check (id = 1),
    engine varchar(20) not null check (engine in ('RULES', 'LOCAL_MODEL'))
);
insert into assistant_setting (id, engine) values (1, 'RULES');

